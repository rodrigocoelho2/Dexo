#!/usr/bin/env python3
"""Builds the page shell and the stylesheet the .NET server serves from LivingDex.WebApi/wwwroot.

  wwwroot/index.html    head + body markup (src/body.html) + the stylesheet and scripts, each with ?v=<hash>
  wwwroot/css/app.css   src/css/*.css in a fixed order, with the blue hues recoloured for the theme picker
  wwwroot/js/*.js       the scripts: edited in place, not built (app.js first, boot.js last)
  wwwroot/data/         pokedex.js and encounters.json, written by data-build/build_data.py

Usage:  python3 LivingDex.Client/build.py   (run again after changing anything in src/, wwwroot/js or wwwroot/data)
"""
import colorsys, hashlib, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'src')
WWW = os.path.normpath(os.path.join(HERE, '..', 'LivingDex.WebApi', 'wwwroot'))

# base → tracker → Showdown → generations → draft → toolbar → profile → map → Daily Red → phone (mob.css last: phone overrides)
CSS = ['base', 'extra', 'sd_base', 'sd_extra', 'sd_b2', 'sd_fx', 'sd_gen', 'sd_draft', 'tb', 'profile', 'where', 'dr', 'mob']
# One global scope: app.js defines the tracker, the others build on it, boot.js renders.
JS = ['app', 'sd', 'dexbadges', 'profile', 'where', 'dr', 'mob', 'boot']


def rd(*p): return open(os.path.join(*p), encoding='utf-8').read()


# The theme picker tints the page by moving one hue (--h) and a saturation factor (--sat): every blue in the
# stylesheet (hue 195–245, not grey) becomes an hsl() relative to the default theme's hue 222.
def _hsl(r, g, b, a=None):
    h, l, sat = colorsys.rgb_to_hls(r / 255, g / 255, b / 255); H = h * 360
    if sat * 100 <= 8 or not (195 <= H <= 245): return None
    dh = round(H - 222); hue = f"calc(var(--h) {'+' if dh >= 0 else '-'} {abs(dh)})"
    return f"hsl({hue} calc({round(sat * 100)}% * var(--sat)) {round(l * 100)}%{'' if a is None else ' / ' + a})"


def _hex(m):
    c = m.group(0)[1:]; c = ''.join(ch * 2 for ch in c) if len(c) == 3 else c
    return _hsl(*(int(c[i:i + 2], 16) for i in (0, 2, 4))) or m.group(0)


def _rgba(m):
    p = [x.strip() for x in m.group(1).split(',')]
    return _hsl(int(p[0]), int(p[1]), int(p[2]), p[3] if len(p) > 3 else None) or m.group(0)


def themeify(c):
    c = re.sub(r'#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b', _hex, c)
    c = re.sub(r'rgba?\(([^)]*)\)', _rgba, c)
    return c.replace(':root{', ':root{\n  --h:222; --sat:1;', 1)


def write(rel, text):
    path = os.path.join(WWW, rel); os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8').write(text)
    print(f'wrote {rel} ({len(text):,} chars)')


def url(rel):
    """/rel?v=<first 10 hex of its sha256>: the files can be cached for good, a change gets a new address."""
    return f"/{rel}?v={hashlib.sha256(open(os.path.join(WWW, rel), 'rb').read()).hexdigest()[:10]}"


css = '/* Generated by LivingDex.Client/build.py from LivingDex.Client/src/css: do not edit. */\n' + themeify('\n'.join(rd(SRC, 'css', n + '.css') for n in CSS))
write('css/app.css', css)

exec(rd(SRC, 'icons.py'))   # FAV_LINK: the Poké Ball favicon (crossed swords while in Showdown)
# Installed as an app on a phone: manifest, iOS web-app tags and launch images (wwwroot/splash, made by splash.py).
SPLASH = [(430, 932, 3), (440, 956, 3), (393, 852, 3), (402, 874, 3), (390, 844, 3), (428, 926, 3), (375, 812, 3), (414, 896, 3), (414, 896, 2), (375, 667, 2), (320, 568, 2)]
head = ('<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
        '<meta name="theme-color" content="#0c1222">\n<title>HOME Living Dex</title>\n' + FAV_LINK + '\n'
        '<link rel="apple-touch-icon" href="/apple-touch-icon.png">\n<link rel="manifest" href="/manifest.json">\n'
        '<meta name="mobile-web-app-capable" content="yes">\n<meta name="apple-mobile-web-app-capable" content="yes">\n'
        '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">\n<meta name="apple-mobile-web-app-title" content="Living Dex">\n'
        + ''.join(f'<link rel="apple-touch-startup-image" media="(device-width: {w}px) and (device-height: {h}px) and (-webkit-device-pixel-ratio: {r}) and (orientation: portrait)" href="/splash/{w * r}x{h * r}.png">\n' for w, h, r in SPLASH)
        + '<style>html{color-scheme:dark}body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style>\n'
        + '<link rel="stylesheet" href="/fonts/fonts.css">\n'
        + f'<link rel="stylesheet" href="{url("css/app.css")}">\n')
scripts = ''.join(f'<script src="{url(rel)}" defer></script>\n' for rel in ['data/pokedex.js'] + [f'js/{n}.js' for n in JS])
page = ('<!doctype html>\n<!-- Generated by LivingDex.Client/build.py: edit src/body.html, src/css or wwwroot/js instead. -->\n'
        '<html lang="en">\n<head>\n' + head + scripts + '</head>\n<body>\n' + rd(SRC, 'body.html').rstrip() + '\n</body>\n</html>\n')
write('index.html', page)
